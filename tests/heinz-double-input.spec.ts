import { expect, test } from "@playwright/test";
import * as XLSX from "xlsx";

test("Return HEINZ: double input tampil di hasil dan ekspor tanpa menjadi masalah", async ({ page }) => {
  const correction = { status: "DOUBLE", invoiceNumber: "CN-025812", customerCode: "C1", principalProductCode: "P1", accurateProductCode: null, accurateQuantity: 0, principalQuantity: 2, quantityDifference: -2, accurateDpp: 0, principalDpp: 30, dppDifference: -30, accurateTax: 0, principalTax: 3, accurateTotal: 0, principalTotal: 33, accurateSourceRows: [], principalSourceRows: [6], warnings: ["Pembatalan akibat input ganda (double input). Keterangan sumber: INV/2609/HZ02101_Batal_DOUBLE INPUT"], invalidReason: null };
  const output = { accurateLines: [], principalLines: [], results: [correction], summary: { MATCH: 0, DOUBLE: 1 }, ignoredLines: [] };
  const json = (body: unknown) => ({ contentType: "application/json", body: JSON.stringify(body) });
  await page.route("**/api/reconciliation/mappings?*", route => route.fulfill(json({ active: { id: "m1", version: 1, originalName: "mapping.xlsx", uploadedByName: "Lokal", createdAt: "2026-10-22T01:00:00Z" }, versions: [], canManage: false })));
  await page.route("**/api/reconciliation/history?*", route => route.fulfill(json({ items: route.request().url().includes("division=returns") ? [{ id: "r1", mappingVersionId: "m1", status: "success", uploadedByName: "Lokal", inputFiles: [], summary: output.summary, issues: [correction], error: null, durationMs: 1, startedAt: "2026-10-22T01:00:00Z" }] : [] })));
  await page.route("**/api/reconciliation/heinz/returns", route => route.fulfill(json(output)));
  await page.goto("/reconciliation");
  const main = page.locator("main");
  await main.getByRole("group", { name: "Jenis Rekonsiliasi" }).getByRole("button", { name: "Return", exact: true }).click();
  await main.getByLabel("Prinsipal", { exact: true }).selectOption("HEINZ");
  await expect(main.getByRole("heading", { level: 1 })).toHaveText("Rekonsiliasi Return HEINZ");
  const upload = { name: "contoh.xlsx", mimeType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", buffer: Buffer.from("PK") };
  await main.locator('input[type="file"]').nth(0).setInputFiles(upload);
  const csvUpload = { name: "contoh.csv", mimeType: "text/csv", buffer: Buffer.from("header\nvalue") };
  await main.locator('input[type="file"]').nth(1).setInputFiles(csvUpload);
  await main.locator('input[type="file"]').nth(2).setInputFiles(csvUpload);
  await main.getByRole("button", { name: "Jalankan rekonsiliasi" }).click();
  await expect(main.locator("#hasil")).toContainText(correction.warnings[0]);
  await expect(main.getByRole("group", { name: "Saring hasil" })).toContainText("Semua 1");
  await expect(main.getByRole("group", { name: "Saring hasil" })).toContainText("Masalah saja 0");
  await main.getByRole("button", { name: "Masalah saja 0" }).click();
  await expect(main.getByText("Tidak ada masalah rekonsiliasi", { exact: true })).toBeVisible();
  await main.getByLabel("Filter status").selectOption("DOUBLE");
  await expect(main.locator("#hasil")).toContainText(correction.warnings[0]);
  const history = main.getByRole("region", { name: "Riwayat rekonsiliasi" });
  await expect(history).toContainText("Total 1");
  await expect(history).toContainText("Double 1");
  await expect(history).toContainText("Masalah 0");
  await history.getByLabel("Lihat rincian r1").click();
  await expect(history).toContainText(correction.warnings[0]);
  const downloaded = page.waitForEvent("download");
  await main.getByRole("button", { name: "Ekspor XLSX" }).click();
  const file = await (await downloaded).path();
  const workbook = XLSX.readFile(file!);
  expect(workbook.SheetNames).toEqual(["Ringkasan", "Detail"]);
  expect(XLSX.utils.sheet_to_json(workbook.Sheets.Detail)).toEqual([expect.objectContaining({ Status: "DOUBLE", "Penyebab selisih": correction.warnings[0] })]);
  await page.locator("#hasil").screenshot({ path: "test-results/heinz-double-input.png" });
});
